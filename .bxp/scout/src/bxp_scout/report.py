"""Weekly report generation for BXP Integration Scout.

Produces a professional, human-readable report of discoveries, scores,
and recommended next steps. Committed to bxp-spec only — never sent to
external repos.
"""

from __future__ import annotations

import json
import time
from pathlib import Path
from typing import Any

from .config import ScoutConfig
from .scout_logging import ScoutLogger


class ReportGenerator:
    """Generates weekly discovery reports."""

    def __init__(self, config: ScoutConfig, logger: ScoutLogger) -> None:
        self.config = config
        self.logger = logger
        self.report_path = Path(config.get("output.report_path", ".bxp/scout/reports/weekly-report.md"))
        self.report_path.parent.mkdir(parents=True, exist_ok=True)

    def generate(
        self,
        candidates: list[dict[str, Any]],
        state: Any,
        run_count: int,
        generated_at: float,
    ) -> Path:
        """Write the weekly report and return its path."""
        lines = self._build_report(candidates, state, run_count, generated_at)
        content = "\n".join(lines)
        self.report_path.write_text(content, encoding="utf-8")
        self.logger.info(f"Report written to {self.report_path}")
        return self.report_path

    def _build_report(
        self,
        candidates: list[dict[str, Any]],
        state: Any,
        run_count: int,
        generated_at: float,
    ) -> list[str]:
        from datetime import datetime, timezone

        generated_iso = datetime.fromtimestamp(generated_at, tz=timezone.utc).isoformat()

        lines = [
            "# BXP Integration Scout — Weekly Report",
            "",
            f"**Generated:** {generated_iso}",
            f"**Run count:** {run_count}",
            f"**Repositories processed (cumulative):** {state.processed_count if state else 'N/A'}",
            f"**Mode:** {self.config.get('scout.mode', 'read-only')}",
            f"**Auto-PR:** {self.config.get('auto_pr_enabled', False)}",
            "",
            "## Summary",
            "",
            f"- Candidates discovered this run: {len(candidates)}",
            f"- Candidates above threshold (>= {self.config.get('scout.min_score_threshold', 0.5)}): "
            f"{sum(1 for c in candidates if c.get('score', 0) >= self.config.get('scout.min_score_threshold', 0.5))}",
            "",
            "## Top Integration Opportunities",
            "",
            "| Rank | Repository | Score | Language | Stars | License | Query |",
            "|------|------------|-------|----------|-------|---------|-------|",
        ]

        for i, c in enumerate(candidates[: self.config.get("scout.max_candidates_per_report", 20)], 1):
            name = c.get("full_name", "unknown")
            score = c.get("score", 0)
            language = c.get("language") or "N/A"
            stars = c.get("stars", 0)
            license_id = c.get("license") or "N/A"
            query = c.get("query", "")
            lines.append(
                f"| {i} | [{name}]({c.get('html_url', '#')}) | {score:.2f} | {language} | {stars} | {license_id} | {query} |"
            )

        lines.append("")
        lines.append("## Recommended Next Steps (Human Review Required)")
        lines.append("")
        lines.append("1. Review the top 3 candidates above for concrete BXP integration value.")
        lines.append("2. Examine generated adapter drafts in `.bxp/scout/adapters/`.")
        lines.append("3. If a candidate warrants integration, a human opens a PR to the external repo.")
        lines.append("4. BXP Scout never opens PRs or issues to external repositories.")
        lines.append("")
        lines.append("## Methodology")
        lines.append("")
        lines.append("- Read-only GitHub repository search via the GitHub Search API")
        lines.append("- Repositories scored on air-quality relevance, API/data surface, activity, and license openness")
        lines.append("- State persistence prevents duplicate discovery across runs")
        lines.append("- All output remains in `bxp-spec/.bxp/scout/` — external repos are never modified")
        lines.append("")
        lines.append("## Generated Adapter Drafts")
        lines.append("")
        lines.append("Adapter sketches are generated for each candidate in `.bxp/scout/adapters/`.")
        lines.append("Each adapter is a draft requiring human review and customization before use.")
        lines.append("")
        lines.append("---")
        lines.append("*Generated by BXP Integration Scout v1.0.0 — Commercial Grade*")

        return lines
